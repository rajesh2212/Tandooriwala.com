import { glob, writeFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'

const SRC = 'vibe_images'
const OUT = 'public/images'

/**
 * These are AI-generated stand-ins for the restaurant's own photography, not
 * pictures of this kitchen. Swap them out (see public/images/README.md) by
 * dropping same-named files in public/images and re-running this script.
 */
const targets = [
  'hero-tandoori',
  'dish-tandoori-chicken',
  'dish-kebabs',
  'dish-curry',
  'dish-biryani',
  'dish-chinese',
  'dish-seafood',
  'dish-dessert',
  'dish-drinks',
  'atmosphere-tandoor',
  'spread-table',
]

const widthLadder = [480, 800, 1024, 1200, 1600]

async function findSource(slug) {
  for await (const file of glob(`${SRC}/${slug}_*.png`)) return file
  throw new Error(`missing source PNG for ${slug}`)
}

const manifest = {}

for (const slug of targets) {
  const src = await findSource(slug)
  const image = sharp(src).rotate()
  const { width: native, height: nativeHeight } = await image.metadata()
  const widths = []
  for (const width of widthLadder) {
    if (width > native) continue
    await image
      .clone()
      .resize({ width, withoutEnlargement: true })
      .jpeg({ quality: 76, progressive: true, mozjpeg: true })
      .toFile(path.join(OUT, `${slug}-${width}.jpg`))
    widths.push(width)
  }
  // largest written file is the fallback src
  manifest[slug] = { widths, ratio: +(native / nativeHeight).toFixed(4) }
  console.log(`ok ${slug} ${widths.join('/')}`)
}

const spread = await findSource('spread-table')
await sharp(spread)
  .resize({ width: 1200, height: 630, fit: 'cover', position: 'centre' })
  .jpeg({ quality: 78, progressive: true, mozjpeg: true })
  .toFile(path.join(OUT, 'og-cover.jpg'))

const banner = `/** Generated by scripts/optimize-images.mjs — do not edit by hand. */\n`
const body = Object.entries(manifest)
  .map(([slug, value]) => `  '${slug}': { widths: [${value.widths.join(', ')}], ratio: ${value.ratio} },`)
  .join('\n')

await writeFile(
  'src/data/imageManifest.ts',
  `${banner}export type ImageEntry = { widths: number[]; ratio: number }

export const images: Record<string, ImageEntry> = {
${body}
}
`,
)
console.log('wrote src/data/imageManifest.ts')
